#!/usr/bin/env python3
"""Generate one OpenAI adapter file per Skill: ``agents/<category>/<skill>/openai.yaml``.

One sidecar serves both OpenAI agents (ChatGPT and Codex) -- see
``docs/multi-agent.md``. The file carries only what OpenAI's skill format
needs beyond SKILL.md: a display name, the short description copied
verbatim from SKILL.md frontmatter, and the implicit-invocation policy
(default true; no skill in this repo is explicit-only today). No MCP or
app dependencies are declared: no skill currently needs one, and none
are invented here. SKILL.md frontmatter stays the single source of
truth; never hand-edit a generated ``openai.yaml``::

    python tools/generate_openai_yaml.py            # write all files
    python tools/generate_openai_yaml.py --check    # fail when any file is stale
    python tools/generate_openai_yaml.py --skill development/code-review

Stale files left behind when a skill is renamed or removed are reported
by ``--check`` and removed by a plain run.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Sequence

if __package__:
    from .generate_skill_yaml import skill_title
    from .layout import ENTRYPOINT, skill_dirs
    from .validator_markdown import frontmatter
else:
    from generate_skill_yaml import skill_title
    from layout import ENTRYPOINT, skill_dirs
    from validator_markdown import frontmatter

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
AGENTS_DIR = "agents"
OPENAI_YAML = "openai.yaml"


def render_openai_yaml(name: str, title: str, description: str) -> str:
    return (
        "# Generated by tools/generate_openai_yaml.py from SKILL.md frontmatter.\n"
        "# Do not hand-edit; re-run the generator. Serves ChatGPT and Codex.\n"
        f"display_name: {title}\n"
        f"short_description: {description}\n"
        "policy:\n"
        "  allow_implicit_invocation: true\n"
        "dependencies: []\n"
    )


def generate(root: Path, only: str | None = None) -> dict[Path, str]:
    generated: dict[Path, str] = {}
    for directory in skill_dirs(root):
        category = directory.parent.parent.name
        route = f"{category}/{directory.name}"
        if only and route != only:
            continue
        text = (directory / ENTRYPOINT).read_text(encoding="utf-8")
        metadata, errors = frontmatter(text)
        if errors or not metadata.get("name") or not metadata.get("description"):
            raise ValueError(f"{directory / ENTRYPOINT}: cannot generate openai.yaml ({errors})")
        name = metadata["name"]
        content = render_openai_yaml(name, skill_title(text, name), metadata["description"])
        generated[root / AGENTS_DIR / category / name / OPENAI_YAML] = content
    if only and not generated:
        raise ValueError(f"no skill matches route '{only}'")
    return generated


def stale_generated_files(root: Path, generated: dict[Path, str]) -> list[str]:
    """openai.yaml files under agents/ that no current skill generates."""
    stale: list[str] = []
    agents_root = root / AGENTS_DIR
    if agents_root.is_dir():
        for path in sorted(agents_root.rglob(OPENAI_YAML)):
            if path not in generated:
                stale.append(path.relative_to(root).as_posix())
    return stale


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--check", action="store_true", help="Fail when a generated file is missing, stale or orphaned.")
    parser.add_argument("--skill", help="Only generate one route, e.g. development/code-review.")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    root = args.root.resolve()
    try:
        generated = generate(root, args.skill)
    except ValueError as error:
        print(f"openai.yaml generation failed: {error}", file=sys.stderr)
        return 1
    if args.check:
        problems = [
            path.relative_to(root).as_posix()
            for path, content in sorted(generated.items())
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ]
        problems.extend(stale_generated_files(root, generated))
        if problems:
            print(
                f"openai.yaml files are out of date: {problems}; run python tools/generate_openai_yaml.py",
                file=sys.stderr,
            )
            return 1
        print(f"openai.yaml files are up to date ({len(generated)})")
        return 0
    for path, content in sorted(generated.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if args.skill is None:
        # Orphan cleanup only makes sense on a full run: a single-skill run
        # must never delete the other skills' files.
        for stale in stale_generated_files(root, generated):
            (root / stale).unlink()
            print(f"removed orphaned {stale}")
    print(f"openai.yaml files written: {len(generated)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
